#ifndef DSO_DECIMATOR_HPP
#define DSO_DECIMATOR_HPP

#include <array>
#include <cstdint>

namespace dso {

enum class DecimationState : std::uint8_t { Invalid, Warming, Accumulating, Output };

struct DecimationResult final {
    DecimationState state{DecimationState::Warming};
    std::uint16_t value{};
    bool raw_clipped{};
    bool output_clamped{};
};

// Fixed two-stage, fivefold-per-stage FIR. The output is the filtered signal,
// not a peak envelope or an assertion of increased ADC resolution. The useful
// passband ends at0.2*output Fs;0.2..0.5*output Fs is the transition band.
// A digital filter cannot reject frequencies already aliased by the raw ADC.
class SlowDecimator final {
public:
    inline static constexpr std::uint16_t Factor{25U};
    inline static constexpr std::uint16_t Taps{63U};
    inline static constexpr std::uint16_t FirstOutputRawSamples{373U};
    inline static constexpr std::uint16_t GroupDelayRawSamples{186U};
    inline static constexpr std::int32_t CoefficientScale{32768};
    // Generated by tools/design-slow-filter.py; symmetric, sum32768 exactly.
    inline static constexpr std::array<std::int16_t, Taps> Coefficients{
        6, 7, 3, -6, -21, -39, -55, -63, -56, -27, 25, 93, 167, 226, 249, 216,
        114, -54, -269, -494, -675, -756, -678, -404, 82, 761, 1579, 2456, 3290,
        3979, 4433, 4590, 4433, 3979, 3290, 2456, 1579, 761, 82, -404, -678,
        -756, -675, -494, -269, -54, 114, 216, 249, 226, 167, 93, 25, -27, -56,
        -63, -55, -39, -21, -6, 3, 7, 6};

    void reset() noexcept;
    // Each call consumes exactly one consecutive12-bit ADC conversion.
    // Invalid input latches Invalid until reset; it never enters the FIR.
    // First output follows373 conversions, then exactly every25 conversions.
    // Both stages are fully primed: no artificial zero-padding is published.
    [[nodiscard]] DecimationResult push(std::uint16_t sample) noexcept;
    [[nodiscard]] bool primed() const noexcept { return primed_; }

private:
    struct Stage final {
        std::array<std::int16_t, Taps> history{};
        std::uint64_t clipped{};
        std::uint8_t cursor{};
        std::uint8_t filled{};
        std::uint8_t remaining{};
        [[nodiscard]] bool push(std::int16_t sample, bool raw_clipped,
                                std::int16_t& output, bool& clipped_output) noexcept;
    };
    Stage first_{};
    Stage second_{};
    bool primed_{};
    bool invalid_{};
};

} // namespace dso
#endif
